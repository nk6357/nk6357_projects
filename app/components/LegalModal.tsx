export function LegalModal({ document, onClose, returnFocusRef }: Props) {
  const panelRef = useRef<HTMLElement>(null);
  useDialog(panelRef, onClose, returnFocusRef);

  return (
    <div className="legal-overlay" role="presentation" onMouseDown={(event) => event.target === event.currentTarget && onClose()}>
      <article ref={panelRef} className="legal-panel" role="dialog" aria-modal="true" aria-labelledby="legal-title" tabIndex={-1}>
        <header>
          <span>Legal / nk6357</span>
          <button type="button" onClick={onClose} data-autofocus>Закрыть <i aria-hidden="true">×</i></button>
        </header>
        <h2 id="legal-title">{titles[document]}</h2>
        <p className="legal-date">Редакция от 5 октября 2026 года</p>
        <div className="legal-content">
          {document === "privacy" && <Privacy />}
          {document === "cookies" && <Cookies />}
          {document === "terms" && <Terms />}
        </div>
      </article>
    </div>
  );
}

